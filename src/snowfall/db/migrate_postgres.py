"""Offline, reversible-by-cutover SQLite v11 -> PostgreSQL migration.

The source SQLite database is opened read-only and copied using SQLite's
WAL-aware online backup API. PostgreSQL must be empty. The import happens in
ONE PostgreSQL transaction, including integrity triggers, metadata and checks.

Run only while the live Discord worker is STOPPED, then verify and opt in.
"""
from __future__ import annotations

import argparse
import base64
from contextlib import closing
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sqlite3
import tempfile

from snowfall.db.store import DB_VERSION
from snowfall.db.postgres import LOCK_KEY, _psycopg

_SAFE = re.compile(r'^[a-z_][a-z_0-9]*$', re.I)
# Explicitly pin the known v11 schema. Refuse unrelated SQLite databases and
# silently missing gameplay tables rather than trusting PRAGMA user_version.
EXPECTED_TABLES = frozenset({
    'players', 'admin_audit', 'season_state', 'published_messages',
    'player_resources', 'combat_events', 'score_ledger', 'player_economy',
    'player_inventory', 'item_events', 'quest_claims', 'mystery_gifts',
    'world_settings', 'world_days', 'world_sieges', 'pve_events',
    'city_day_snapshots', 'launch_approvals', 'prize_awards', 'player_titles',
    'cosmetic_unlocks', 'cosmetic_equipped', 'cosmetic_purchases',
    'encounter_events', 'arcade_events', 'mystery_clues', 'mystery_guesses',
    'mystery_secrets', 'social_arcade_runs', 'social_arcade_turns',
    'social_arcade_stamps', 'wire_submissions', 'wire_decisions',
})


class MigrationError(RuntimeError):
    pass


def _identifier(name: str):
    if not _SAFE.fullmatch(name):
        raise MigrationError(f'Unexpected schema identifier: {name!r}')
    return name


def convert_table_ddl(sql: str) -> str:
    """Translate already-upgraded SQLite table DDL into PostgreSQL DDL."""
    if not re.match(r'^CREATE\s+TABLE\b', sql, re.I):
        raise MigrationError('Expected CREATE TABLE statement')
    sql = re.sub(r'\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b',
                 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql, flags=re.I)
    sql = re.sub(r'\bINTEGER\b', 'BIGINT', sql, flags=re.I)
    sql = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', sql, flags=re.I)
    sql = re.sub(r'\bBLOB\b', 'BYTEA', sql, flags=re.I)
    # SQLite INTEGER affinity permits fractional pause durations from the
    # event clock. PostgreSQL BIGINT would round or reject them.
    sql = re.sub(r'\bpaused_seconds\s+BIGINT\b',
                 'paused_seconds DOUBLE PRECISION', sql, flags=re.I)
    return sql


def _snapshot(source: Path, output: Path):
    if not source.is_file():
        raise MigrationError(f'Cannot find SQLite source at {source}')
    # A read-only original is never modified. SQLite handles any WAL pages
    # consistently when backup() is performed.
    with closing(sqlite3.connect(source.as_uri() + '?mode=ro', uri=True, timeout=15)) as original:
        if original.execute('PRAGMA quick_check').fetchone()[0] != 'ok':
            raise MigrationError('SQLite source integrity check failed')
        version = original.execute('PRAGMA user_version').fetchone()[0]
        if version != DB_VERSION:
            raise MigrationError(f'Expected SQLite schema v{DB_VERSION}; found v{version}')
        with closing(sqlite3.connect(output)) as target:
            original.backup(target)
            if target.execute('PRAGMA quick_check').fetchone()[0] != 'ok':
                raise MigrationError('SQLite snapshot integrity check failed')


def _schema(sqlite):
    rows = sqlite.execute("SELECT type,name,tbl_name,sql FROM sqlite_master "
                          "WHERE type IN ('table','index','trigger') AND sql IS NOT NULL "
                          "ORDER BY rowid").fetchall()
    tables, indexes, triggers = [], [], []
    for kind, name, table, statement in rows:
        if name.startswith('sqlite_'):
            continue
        _identifier(name)
        _identifier(table)
        if kind == 'table':
            tables.append((name, statement))
        elif kind == 'index':
            indexes.append((name, statement))
        elif kind == 'trigger':
            triggers.append((name, table, statement))
    observed_tables = {name for name, _ in tables}
    if observed_tables != EXPECTED_TABLES or len(tables) != len(EXPECTED_TABLES):
        missing = sorted(EXPECTED_TABLES - observed_tables)
        extra = sorted(observed_tables - EXPECTED_TABLES)
        raise MigrationError(f'Unexpected v11 schema: missing={missing}, extra={extra}')
    if any(not name.startswith('idx_') for name, _ in indexes):
        raise MigrationError('Source contains an unexpected named index')
    return tables, indexes, triggers


def _norm(value):
    if isinstance(value, float) and value.is_integer():
        # PostgreSQL DOUBLE PRECISION yields 0.0 for the old INTEGER-affinity
        # paused_seconds column, whose SQLite source may contain integer 0.
        return int(value)
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, (bytes, bytearray, memoryview)):
        return {'__blob__': base64.b64encode(bytes(value)).decode('ascii')}
    # PostgreSQL may return Decimal for SUM/NUMERIC but stored columns are
    # migrated to BIGINT/DOUBLE PRECISION, so unexpected types are refused.
    raise MigrationError(f'Cannot fingerprint {type(value).__name__}')


def _digest(rows):
    serialized = [json.dumps([_norm(val) for val in row], ensure_ascii=True,
                             sort_keys=True, separators=(',', ':'), allow_nan=False)
                  for row in rows]
    digest = hashlib.sha256()
    for row in sorted(serialized):
        digest.update(row.encode('utf-8'))
        digest.update(b'\n')
    return len(rows), digest.hexdigest()


def _sqlite_rows(db, table):
    return db.execute(f'SELECT * FROM "{_identifier(table)}"').fetchall()


def _pg_rows(cursor, table):
    cursor.execute(f'SELECT * FROM "{_identifier(table)}"')
    return cursor.fetchall()


def _create_integrity_triggers(cur, triggers):
    """Port immutable-history triggers and the arcade session state machine.

    These triggers must be installed after the data import, just like on SQLite
    initial schema initialization (the source itself is already immutable).
    """
    cur.execute("""
        CREATE FUNCTION snowfall_reject_change() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            RAISE EXCEPTION 'immutable Snowfall game history' USING ERRCODE = '23514';
        END
        $$
    """)
    cur.execute("""
        CREATE FUNCTION snowfall_arcade_identity() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            IF OLD.session_id IS DISTINCT FROM NEW.session_id OR
               OLD.season_key IS DISTINCT FROM NEW.season_key OR
               OLD.discord_user_id IS DISTINCT FROM NEW.discord_user_id OR
               OLD.day IS DISTINCT FROM NEW.day OR
               OLD.mode IS DISTINCT FROM NEW.mode OR
               OLD.attempt IS DISTINCT FROM NEW.attempt OR
               OLD.puzzles_json IS DISTINCT FROM NEW.puzzles_json OR
               OLD.started_at_utc IS DISTINCT FROM NEW.started_at_utc OR
               OLD.status = 'finished' OR
               NEW.step < OLD.step OR NEW.score < OLD.score THEN
                RAISE EXCEPTION 'arcade run integrity' USING ERRCODE = '23514';
            END IF;
            RETURN NEW;
        END
        $$
    """)
    for name, table, statement in triggers:
        if re.search(r'\bBEFORE\s+UPDATE\b', statement, re.I):
            event = 'UPDATE'
        elif re.search(r'\bBEFORE\s+DELETE\b', statement, re.I):
            event = 'DELETE'
        else:
            raise MigrationError(f'Unhandled source trigger {name}')
        if name == 'social_arcade_runs_identity':
            if event != 'UPDATE':
                raise MigrationError('Arcade trigger mismatch')
            function = 'snowfall_arcade_identity'
        elif name.endswith(('_immutable_update', '_immutable_delete')) or name == 'social_arcade_runs_no_delete':
            function = 'snowfall_reject_change'
        else:
            raise MigrationError(f'Refusing to silently omit trigger {name}')
        cur.execute(f'CREATE TRIGGER "{name}" BEFORE {event} ON "{table}" '
                    f'FOR EACH ROW EXECUTE FUNCTION {function}()')


def _import(source_snapshot: Path, dsn: str):
    psycopg = _psycopg()
    from psycopg import sql
    with closing(sqlite3.connect(source_snapshot)) as sqlite:
        tables, indexes, triggers = _schema(sqlite)
        source_summary = {table: _digest(_sqlite_rows(sqlite, table)) for table, _ in tables}
        source_hash = hashlib.sha256(source_snapshot.read_bytes()).hexdigest()
        with psycopg.connect(dsn, autocommit=False, connect_timeout=15) as postgres:
            with postgres.cursor() as cur:
                cur.execute('SELECT pg_advisory_xact_lock(%s)', (LOCK_KEY,))
                cur.execute("SELECT tablename FROM pg_tables WHERE schemaname=current_schema()")
                existing = [row[0] for row in cur.fetchall()]
                if existing:
                    raise MigrationError('PostgreSQL target is not empty; refusing overwrite: ' +
                                         ', '.join(existing[:8]))
                for table, definition in tables:
                    cur.execute(convert_table_ddl(definition))
                for table, _ in tables:
                    values = _sqlite_rows(sqlite, table)
                    if not values:
                        continue
                    columns = [row[1] for row in sqlite.execute(f'PRAGMA table_info("{table}")')]
                    statement = sql.SQL('INSERT INTO {} ({}) VALUES ({})').format(
                        sql.Identifier(table),
                        sql.SQL(', ').join(map(sql.Identifier, columns)),
                        sql.SQL(', ').join(sql.Placeholder() for _ in columns),
                    )
                    cur.executemany(statement, values)
                for name, definition in indexes:
                    cur.execute(definition)
                # Generate next IDs after copying historical primary keys.
                for table, _ in tables:
                    rows = sqlite.execute(f'PRAGMA table_info("{table}")').fetchall()
                    if not any(row[1] == 'id' and row[5] == 1 for row in rows):
                        continue
                    # wire_decisions has an externally supplied PK; no identity
                    # sequence exists for it and none should be created.
                    cur.execute('SELECT pg_get_serial_sequence(%s,%s)', (table, 'id'))
                    seq = cur.fetchone()[0]
                    if seq:
                        cur.execute(sql.SQL('SELECT MAX({}) FROM {}').format(
                            sql.Identifier('id'), sql.Identifier(table)))
                        maximum = cur.fetchone()[0]
                        cur.execute('SELECT setval(%s, %s, %s)',
                                    (seq, maximum if maximum else 1, bool(maximum)))
                _create_integrity_triggers(cur, triggers)
                cur.execute('CREATE TABLE snowfall_pg_meta ('
                            'singleton BIGINT PRIMARY KEY CHECK(singleton=1), '
                            'version BIGINT NOT NULL, source_sha256 TEXT NOT NULL, '
                            'migrated_at_utc TEXT NOT NULL)')
                cur.execute('INSERT INTO snowfall_pg_meta VALUES (%s,%s,%s,%s)',
                            (1, DB_VERSION, source_hash, datetime.now(timezone.utc).isoformat()))
                for table, _ in tables:
                    expected = source_summary[table]
                    actual = _digest(_pg_rows(cur, table))
                    if expected != actual:
                        raise MigrationError(f'Migration mismatch in {table}: '
                                             f'SQLite={expected}, PostgreSQL={actual}')
                # No commit is possible before the entire import, triggers,
                # constraints and per-table checks have succeeded.
            return {
                'schema_version': DB_VERSION, 'tables': len(tables),
                'triggers': len(triggers), 'indexes': len(indexes),
                'rows': sum(size for size, _ in source_summary.values()),
                'source_sha256': source_hash,
            }


def verify(source: Path, dsn: str):
    psycopg = _psycopg()
    with tempfile.TemporaryDirectory(prefix='snowfall-pg-verify-') as temp:
        snapshot = Path(temp) / 'verified.sqlite3'
        _snapshot(source, snapshot)
        with closing(sqlite3.connect(snapshot)) as sqlite:
            tables, _, _ = _schema(sqlite)
            summary = {table: _digest(_sqlite_rows(sqlite, table)) for table, _ in tables}
            with psycopg.connect(dsn, autocommit=False, connect_timeout=15) as pg:
                with pg.cursor() as cur:
                    cur.execute('SELECT version FROM snowfall_pg_meta WHERE singleton=1')
                    row = cur.fetchone()
                    if row is None or row[0] != DB_VERSION:
                        raise MigrationError('PG schema metadata is not v11')
                    for table, _ in tables:
                        if summary[table] != _digest(_pg_rows(cur, table)):
                            raise MigrationError(f'PostgreSQL differs from SQLite in {table}')
        return {'schema_version': DB_VERSION, 'tables': len(tables),
                'rows': sum(size for size, _ in summary.values()), 'matching': True}


def migrate(source: Path, dsn: str, *, confirmation: str):
    if confirmation != 'OFFLINE_MIGRATE':
        raise MigrationError('Stop the live bot, then explicitly pass --confirm OFFLINE_MIGRATE')
    with tempfile.TemporaryDirectory(prefix='snowfall-pg-migrate-') as temp:
        snapshot = Path(temp) / 'consistent.sqlite3'
        _snapshot(source, snapshot)
        return _import(snapshot, dsn)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Offline Operation Snowfall v2.9.2 PostgreSQL migration')
    parser.add_argument('--sqlite', required=True, type=Path,
                        help='Path to a verified SQLite v11 source file')
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--inspect', action='store_true', help='Read-only source inventory')
    mode.add_argument('--migrate', action='store_true', help='Copy into EMPTY PostgreSQL database')
    mode.add_argument('--verify', action='store_true', help='Read-only per-table verification')
    parser.add_argument('--dsn-env', default='SNOWFALL_DATABASE_URL',
                        help='Environment variable containing PostgreSQL URL (never printed)')
    parser.add_argument('--confirm', default='')
    args = parser.parse_args(argv)
    try:
        import os
        if args.inspect:
            with tempfile.TemporaryDirectory(prefix='snowfall-pg-inspect-') as temp:
                snapshot = Path(temp) / 'consistent.sqlite3'
                _snapshot(args.sqlite, snapshot)
                with closing(sqlite3.connect(snapshot)) as db:
                    tables, indexes, triggers = _schema(db)
                    result = {'schema_version': DB_VERSION, 'tables': len(tables),
                              'indexes': len(indexes), 'triggers': len(triggers),
                              'rows': sum(len(_sqlite_rows(db, table)) for table, _ in tables)}
        else:
            dsn = os.environ.get(args.dsn_env, '')
            if not dsn:
                raise MigrationError(f'Environment variable {args.dsn_env} is not set')
            result = migrate(args.sqlite, dsn, confirmation=args.confirm) if args.migrate else verify(args.sqlite, dsn)
        print(json.dumps(result, indent=2))
        return 0
    except (MigrationError, sqlite3.DatabaseError, RuntimeError, OSError) as exc:
        parser.exit(2, f'MIGRATION REFUSED: {exc}\n')
    except Exception as exc:
        # Never echo an unexpected driver error that may embed a private DSN.
        parser.exit(2, f'MIGRATION REFUSED: {type(exc).__name__}; check private connection settings\n')


if __name__ == '__main__':
    raise SystemExit(main())
