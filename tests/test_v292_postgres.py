"""v2.9.2: backend selection, SQL translation and migration safety contracts."""
from __future__ import annotations

from datetime import datetime, timezone
import os
from types import SimpleNamespace

import pytest

from snowfall.db.postgres import (
    CompatibleRow, PostgresStore, compatible_row_factory, make_store, translate_sql,
)
from snowfall.db.migrate_postgres import (
    MigrationError, convert_table_ddl, migrate, verify,
)
from snowfall.db.store import DB_VERSION, Store


def test_backend_is_opt_in(tmp_path):
    assert type(make_store(tmp_path / 'snowfall.sqlite3', environment={})) is Store
    assert type(make_store(tmp_path / 'snowfall.sqlite3', environment={
        'SNOWFALL_DB_BACKEND': 'sqlite',
        'SNOWFALL_DATABASE_URL': 'postgresql://example',
    })) is Store
    with pytest.raises(ValueError, match='SNOWFALL_DATABASE_URL'):
        make_store(tmp_path / 'snowfall.sqlite3', environment={'SNOWFALL_DB_BACKEND': 'postgres'})
    with pytest.raises(ValueError, match='sqlite or postgres'):
        make_store(tmp_path / 'snowfall.sqlite3', environment={'SNOWFALL_DB_BACKEND': 'unexpected'})
    postgres = make_store(tmp_path / 'snowfall.sqlite3', environment={
        'SNOWFALL_DB_BACKEND': 'postgres',
        'SNOWFALL_DATABASE_URL': 'postgresql://example/db',
    })
    assert isinstance(postgres, PostgresStore)
    assert postgres.path.parent == tmp_path


def test_sql_translation_preserves_aggregates_and_prevents_double_inserts():
    assert translate_sql('SELECT MAX(score),MIN(score) FROM ledger WHERE id=?') == (
        'SELECT MAX(score),MIN(score) FROM ledger WHERE id=%s'
    )
    assert translate_sql('UPDATE t SET points=MIN(100,points+?) WHERE id=?') == (
        'UPDATE t SET points=LEAST(100,points+%s) WHERE id=%s'
    )
    assert translate_sql('SELECT MIN(l.points, COALESCE(c.credit,l.points))') == (
        'SELECT LEAST(l.points, COALESCE(c.credit,l.points))'
    )
    assert translate_sql('INSERT OR IGNORE INTO player_resources (id) VALUES (?)') == (
        'INSERT INTO player_resources (id) VALUES (%s) ON CONFLICT DO NOTHING'
    )
    assert translate_sql("SELECT '?' AS literal, col FROM t WHERE x=?") == (
        "SELECT '?' AS literal, col FROM t WHERE x=%s"
    )
    assert translate_sql('SELECT 1 /* ? */ WHERE id=? -- ?') == (
        'SELECT 1 /* ? */ WHERE id=%s -- ?'
    )


def test_sqlite_compatible_row():
    row = CompatibleRow(('name', 'score'), ('Player', 42))
    assert row['name'] == 'Player' and row[0] == 'Player' and row[1] == 42
    assert row.keys() == ['name', 'score']
    assert dict(row) == {'name': 'Player', 'score': 42}
    assert tuple(row) == ('Player', 42)


def test_row_factory_supports_dml_with_no_result_columns():
    """Psycopg constructs row factories for command-only statements too.

    This covers the exact failure in the v2.9.2 PostgreSQL CI job:
    INSERT ... ON CONFLICT DO NOTHING leaves cursor.description as None.
    """
    no_result = SimpleNamespace(description=None)
    factory = compatible_row_factory(no_result)
    record = factory(())
    assert tuple(record) == () and record.keys() == []
    assert record.items() == {}.items()

    with_result = SimpleNamespace(description=(SimpleNamespace(name='name'),
                                               SimpleNamespace(name='score')))
    record = compatible_row_factory(with_result)(('Snow Dude', 42))
    assert record[0] == record['name'] == 'Snow Dude'
    assert record[1] == record['score'] == 42


def test_schema_translation_supports_identity_and_big_discord_ids():
    ddl = convert_table_ddl('CREATE TABLE players ('
                            'id INTEGER PRIMARY KEY AUTOINCREMENT, '
                            'discord_user_id INTEGER NOT NULL, '
                            'warmth REAL, city TEXT, '
                            'UNIQUE(discord_user_id))')
    assert 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in ddl
    assert 'discord_user_id BIGINT' in ddl and 'DOUBLE PRECISION' in ddl
    assert 'UNIQUE(discord_user_id)' in ddl
    pause = convert_table_ddl('CREATE TABLE season_state (paused_seconds INTEGER NOT NULL DEFAULT 0)')
    assert 'paused_seconds DOUBLE PRECISION NOT NULL' in pause


def test_migration_requires_explicit_confirmation(tmp_path):
    with pytest.raises(MigrationError, match='OFFLINE_MIGRATE'):
        migrate(tmp_path / 'anything.sqlite3', 'postgresql://ignored', confirmation='')


@pytest.mark.skipif(not os.getenv('SNOWFALL_PG_TEST_DSN') or
                    os.getenv('SNOWFALL_PG_TEST_CONFIRM') != 'EMPTY_TEST_DATABASE',
                    reason='Only an explicitly provisioned EMPTY test Postgres DB may be used')
def test_real_postgres_offline_migration_and_gameplay(tmp_path):
    # This test is designed for GitHub CI's disposable postgres service. It
    # MUST NOT be run against a populated production database.

    source = tmp_path / 'source.sqlite3'
    store = Store(source)
    store.initialize()
    start = datetime(2026, 12, 20, 19, tzinfo=timezone.utc)
    store.ensure_season('pg-test-2026', start)
    store.register('pg-test-2026', 101, 'TesterOne', 'Chicago', start)
    with store.connect() as con:
        con.execute("INSERT INTO score_ledger (season_key,day,player_id,city,category,points,source_key,created_at_utc) "
                    "VALUES(?,?,?,?,?,?,?,?)", ('pg-test-2026',1,101,'Chicago','manual',9,'one','2026-12-20T19:00:00+00:00'))

    dsn = os.environ['SNOWFALL_PG_TEST_DSN']
    result = migrate(source, dsn, confirmation='OFFLINE_MIGRATE')
    assert result['schema_version'] == DB_VERSION and result['rows'] >= 3
    assert verify(source, dsn)['matching']

    pg_store = PostgresStore(dsn, practice_root=tmp_path)
    pg_store.initialize()
    assert pg_store.schema_version() == DB_VERSION
    assert pg_store.season('pg-test-2026').planned_start == start
    assert len(pg_store.registrations('pg-test-2026')) == 1
    assert pg_store.ensure_season('pg-test-2026', start).planned_start == start
    # PostgreSQL has no SQLite rowid pseudo-column. Both raid history and
    # final-result replay must use deterministic persisted timestamps and IDs.
    from snowfall.services.world import WorldEngine
    from snowfall.services.boss_raid import RaidEngine

    class FixedBossRoll:
        def random(self):
            return 0.0

    pg_store.transition('pg-test-2026', 900, 'start', start, 'PostgreSQL staging QA')
    WorldEngine(pg_store, FixedBossRoll()).tick('pg-test-2026', start)
    with pg_store.connect() as con:
        con.execute('UPDATE world_days SET boss_hp=12,boss_initial_hp=12 '
                    'WHERE season_key=? AND day=1', ('pg-test-2026',))
    final_boss = WorldEngine(pg_store, FixedBossRoll()).attack(
        'pg-test-2026', 101, 'boss', 'pg-qa-final', start,
    )
    report = RaidEngine(pg_store).report('pg-test-2026', 1)
    assert final_boss.final_blow and report.defeated and report.remaining_hp == 0
    assert report.shared_damage == 12 and report.contributors == 1
    assert RaidEngine(pg_store).final_result('pg-test-2026', 1).interaction_id == 'pg-qa-final'
    assert WorldEngine(pg_store).attack(
        'pg-test-2026', 101, 'boss', 'pg-qa-final', start,
    ).repeated
    # One inserted Wire story must expose SQLite-compatible lastrowid.
    with pg_store.connect() as con:
        inserted = con.execute(
            'INSERT INTO wire_submissions '
            '(interaction_id,season_key,discord_user_id,day,title,body,created_at_utc) '
            'VALUES(?,?,?,?,?,?,?)',
            ('story-1', 'pg-test-2026', 101, 1, 'A Winter Story',
             'An original and sufficiently long winter tale.', start.isoformat()),
        )
        assert inserted.lastrowid == 1
    # The progress monotonicity trigger is part of the game state contract.
    with pg_store.connect() as con:
        con.execute(
            'INSERT INTO social_arcade_runs '
            '(session_id,season_key,discord_user_id,day,mode,attempt,puzzles_json,started_at_utc) '
            'VALUES(?,?,?,?,?,?,?,?)',
            ('arcade-1','pg-test-2026',101,1,'gallery',1,'[]',start.isoformat()),
        )
        con.execute('UPDATE social_arcade_runs SET step=1,score=10 WHERE session_id=?',
                    ('arcade-1',))
    with pytest.raises(Exception):
        with pg_store.connect() as con:
            con.execute('UPDATE social_arcade_runs SET step=0 WHERE session_id=?',
                        ('arcade-1',))
    # The existing registration conflict must be raised by the same service.
    from snowfall.db.store import RegistrationError
    with pytest.raises(RegistrationError, match='already been claimed'):
        pg_store.register('pg-test-2026', 102, 'TesterOne', 'Detroit', start)
    with pg_store.connect() as con:
        assert con.execute("SELECT SUM(points) FROM score_ledger WHERE season_key=? AND category='manual'",
                           ('pg-test-2026',)).fetchone()[0] == 9
        assert con.execute('SELECT COUNT(*) FROM players').fetchone()[0] == 1
    # Existing immutability guarantees must hold at the PostgreSQL level.
    with pytest.raises(Exception):
        with pg_store.connect() as con:
            con.execute('UPDATE score_ledger SET points=100 WHERE source_key=?', ('one',))
    with pytest.raises(MigrationError, match='not empty'):
        migrate(source, dsn, confirmation='OFFLINE_MIGRATE')
